# --- DATA LOADING & PREPROCESSING ---
@st.cache_data(ttl=600)
def load_data():
    sheet_id = "164l9v3nGrUTrgC3R_pt2bcX2FgZb2tGvcODtE55Efkk"
    gid = "0"
    url = f"https://docs.google.com/spreadsheets/d/{sheet_id}/export?format=csv&gid={gid}"

    df = pd.read_csv(url)

    # Clean column names
    df.columns = df.columns.str.strip()

    # Parse Date
    df['Date'] = pd.to_datetime(df['Date'], errors='coerce')

    # Ensure numeric QTY
    df['QTY'] = pd.to_numeric(df['QTY'], errors='coerce').fillna(0)

    # Parse EnquiryReceivedTime and ReplyTime to compute Reply Time Variance (in minutes)
    def parse_time_diff(row):
        try:
            date_str = row['Date'].strftime('%Y-%m-%d')
            recv_time = pd.to_datetime(f"{date_str} {row['EnquiryReceivedTime']}", errors='coerce')
            reply_time = pd.to_datetime(f"{date_str} {row['ReplyTime']}", errors='coerce')

            if pd.notnull(recv_time) and pd.notnull(reply_time):
                # Handles next-day replies if reply time < received time
                if reply_time < recv_time:
                    reply_time += pd.Timedelta(days=1)
                return (reply_time - recv_time).total_seconds() / 60.0
        except Exception:
            return None
        return None

    df['Reply_Variance_Mins'] = df.apply(parse_time_diff, axis=1)

    return df

try:
    data = load_data()
except Exception as e:
    st.error(f"Error loading Google Sheet data: {e}")
    st.stop()

# --- SIDEBAR FILTERS & DATE COMPARISON ---
st.sidebar.header("🗓️ Date Filters & Options")

min_date = data['Date'].min().date() if not data['Date'].isna().all() else pd.to_datetime("today").date()
max_date = data['Date'].max().date() if not data['Date'].isna().all() else pd.to_datetime("today").date()

mode = st.sidebar.radio("Select View Mode:", ["Single Date Range / Standard View", "Compare Date Ranges"])

if mode == "Single Date Range / Standard View":
    selected_range = st.sidebar.date_input("Select Date Range", [min_date, max_date])
    if len(selected_range) == 2:
        start_date, end_date = selected_range
        df_filtered = data[(data['Date'].dt.date >= start_date) & (data['Date'].dt.date <= end_date)]
    else:
        df_filtered = data.copy()

    st.markdown(f"### Showing Data from **{start_date}** to **{end_date}**")

else:
    col_p1, col_p2 = st.sidebar.columns(2)
    with col_p1:
        st.subheader("Period 1")
        range1 = st.sidebar.date_input("Period 1 Range", [min_date, max_date], key="r1")
    with col_p2:
        st.subheader("Period 2")
        range2 = st.sidebar.date_input("Period 2 Range", [min_date, max_date], key="r2")

    if len(range1) == 2 and len(range2) == 2:
        df_p1 = data[(data['Date'].dt.date >= range1[0]) & (data['Date'].dt.date <= range1[1])]
        df_p2 = data[(data['Date'].dt.date >= range2[0]) & (data['Date'].dt.date <= range2[1])]
    else:
        df_p1, df_p2 = data.copy(), data.copy()

    df_filtered = pd.concat([df_p1, df_p2])  # combined view for simple aggregated metrics

